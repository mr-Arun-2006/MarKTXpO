// Deterministic helper to generate realistic OHLCV historical daily data for Indian equities
function generateHistoricalCandles(basePrice: number, days = 120, trend = 0.0006, volatility = 0.015): OHLCVCandle[] {
  const candles: OHLCVCandle[] = [];
  let currentPrice = basePrice * (1 - days * 0.001);
  const now = new Date();

  for (let i = days; i >= 0; i--) {
    const d = new Date(now);
    d.setDate(d.getDate() - i);
    // skip weekends
    if (d.getDay() === 0 || d.getDay() === 6) continue;

    const dateStr = d.toISOString().split('T')[0];
    const dailyReturn = (Math.sin(i * 0.4) * 0.008) + trend + ((Math.random() - 0.48) * volatility * 2);
    const open = Math.round(currentPrice * 100) / 100;
    const close = Math.round(open * (1 + dailyReturn) * 100) / 100;
    const high = Math.round(Math.max(open, close) * (1 + Math.random() * 0.012) * 100) / 100;
    const low = Math.round(Math.min(open, close) * (1 - Math.random() * 0.012) * 100) / 100;
    const volume = Math.floor(800000 + Math.random() * 4500000);
    
    // Slight tick spread between NSE and BSE
    const spreadDelta = Math.round((Math.random() - 0.5) * (open * 0.0008) * 100) / 100;
    const nseClose = close;
    const bseClose = Math.round((close + spreadDelta) * 100) / 100;

    candles.push({
      date: dateStr,
      open,
      high,
      low,
      close,
      volume,
      nseClose,
      bseClose,
    });

    currentPrice = close;
  }
  return candles;
}

// Calculate RSI helper
function calculateRSI(candles: OHLCVCandle[], period = 14): number {
  if (candles.length < period + 1) return 50;
  let gains = 0;
  let losses = 0;
  for (let i = candles.length - period; i < candles.length; i++) {
    const diff = candles[i].close - candles[i - 1].close;
    if (diff >= 0) gains += diff;
    else losses += Math.abs(diff);
  }
  const avgGain = gains / period;
  const avgLoss = losses / period;
  if (avgLoss === 0) return 100;
  const rs = avgGain / avgLoss;
  return Math.round((100 - (100 / (1 + rs))) * 10) / 10;
}

