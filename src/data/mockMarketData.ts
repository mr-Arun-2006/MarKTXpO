// Build complete stock database
export function buildStockDatabase(): StockData[] {
  return RAW_STOCKS.map((s) => {
    const history = generateHistoricalCandles(s.basePrice, 100);
    const latest = history[history.length - 1];
    const prev = history[history.length - 2] || latest;
    
    const nsePrice = latest.close;
    const bsePrice = Math.round((nsePrice + s.arbitrageBias) * 100) / 100;
    const currentPrice = nsePrice;
    const previousClose = prev.close;
    const change = Math.round((currentPrice - previousClose) * 100) / 100;
    const changePercent = Math.round(((change / previousClose) * 100) * 100) / 100;

    const rsi = calculateRSI(history);
    
    // Calculate simple indicators
    const closes = history.map((c) => c.close);
    const dma20 = Math.round((closes.slice(-20).reduce((a, b) => a + b, 0) / 20) * 100) / 100;
    const dma50 = Math.round((closes.slice(-50).reduce((a, b) => a + b, 0) / 50) * 100) / 100;
    const dma200 = Math.round((closes.slice(-100).reduce((a, b) => a + b, 0) / Math.min(100, closes.length)) * 100) / 100;

    // Bollinger bands
    const stdDev20 = Math.sqrt(
      closes.slice(-20).reduce((acc, val) => acc + Math.pow(val - dma20, 2), 0) / 20
    );
    const bbUpper = Math.round((dma20 + 2 * stdDev20) * 100) / 100;
    const bbLower = Math.round((dma20 - 2 * stdDev20) * 100) / 100;

    // MACD approximation
    const macdLine = Math.round((dma20 - dma50) * 10) / 10;
    const signalLine = Math.round((macdLine * 0.85) * 10) / 10;
    const histogram = Math.round((macdLine - signalLine) * 10) / 10;

    const spreadPercent = Math.round(((nsePrice - bsePrice) / nsePrice * 100) * 1000) / 1000;
    const arbitrageDirection =
      spreadPercent > 0.03 ? 'BUY_BSE_SELL_NSE' : spreadPercent < -0.03 ? 'BUY_NSE_SELL_BSE' : 'PARITY';
    const potentialArbitrageProfitPer1000Shares = Math.round(Math.abs(nsePrice - bsePrice) * 1000);

    const sentimentLabel =
      s.sentimentScore > 75
        ? 'Very Bullish'
        : s.sentimentScore > 60
        ? 'Bullish'
        : s.sentimentScore > 40
        ? 'Neutral'
        : s.sentimentScore > 20
        ? 'Bearish'
        : 'Very Bearish';

    // Hourly price movement calculation (latest hour vs previous hour)
    const hourlySeed = ((s.basePrice * 17 + s.sentimentScore * 11) % 100) / 100;
    const hourlyChangePercent = Math.round((hourlySeed * 1.6 - 0.75 + (changePercent * 0.35)) * 100) / 100;
    const hourlyChange = Math.round((currentPrice * (hourlyChangePercent / 100)) * 100) / 100;
    const hourlyTrend: 'UP' | 'DOWN' | 'NEUTRAL' =
      hourlyChangePercent > 0.05 ? 'UP' : hourlyChangePercent < -0.05 ? 'DOWN' : 'NEUTRAL';

    // Dividend tracking metrics
    const annualDividendPerShare = Math.round(currentPrice * (s.dividendYield / 100) * 10) / 10;
    const payoutRatio = Math.round((36 + (s.dividendYield * 11) + (Math.sin(s.basePrice) * 8)) * 10) / 10;
    const upcomingDayOffset = (Math.abs(Math.floor(s.basePrice)) % 42) + 4;
    const nextDivDate = new Date();
    nextDivDate.setDate(nextDivDate.getDate() + upcomingDayOffset);
    const upcomingDividendDate = nextDivDate.toISOString().split('T')[0];
    const upcomingDividendAmount = Math.round((annualDividendPerShare / (s.dividendYield > 3 ? 3 : 2)) * 10) / 10;

    return {
      ticker: s.ticker,
      bseCode: s.bseCode,
      name: s.name,
      sector: s.sector,
      nsePrice,
      bsePrice,
      currentPrice,
      previousClose,
      change,
      changePercent,
      open: latest.open,
      high: latest.high,
      low: latest.low,
      volume: latest.volume,
      nseVolume: Math.floor(latest.volume * 0.78),
      bseVolume: Math.floor(latest.volume * 0.22),
      marketCapCr: s.marketCapCr,
      pe: s.pe,
      pb: s.pb,
      dividendYield: s.dividendYield,
      annualDividendPerShare,
      payoutRatio,
      upcomingDividendDate,
      upcomingDividendAmount,
      hourlyChange,
      hourlyChangePercent,
      hourlyTrend,
      high52: Math.round(s.basePrice * 1.18 * 10) / 10,
      low52: Math.round(s.basePrice * 0.76 * 10) / 10,
      beta: s.beta,
      rsi,
      macd: {
        macdLine,
        signalLine,
        histogram,
        signal: histogram > 0 ? 'Bullish' : histogram < 0 ? 'Bearish' : 'Neutral',
      },
      dma20,
      dma50,
      dma200,
      bollingerBands: {
        upper: bbUpper,
        middle: dma20,
        lower: bbLower,
      },
      deliveryPercent: Math.round((42 + (Math.sin(s.basePrice) * 15)) * 10) / 10,
      upperCircuit: Math.round(currentPrice * 1.10 * 10) / 10,
      lowerCircuit: Math.round(currentPrice * 0.90 * 10) / 10,
      spreadPercent,
      arbitrageDirection,
      potentialArbitrageProfitPer1000Shares,
      sentiment: {
        score: s.sentimentScore,
        label: sentimentLabel,
        confidence: s.confidence,
        newsScore: s.newsScore,
        socialScore: s.socialScore,
        institutionalScore: s.institutionalScore,
        keyCatalyst: s.keyCatalyst,
      },
      history,
    };
  });
}

